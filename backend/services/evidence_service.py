    def restore_evidence_for_demo(self, evidence_id: str) -> Dict[str, Any]:
        """
        Restores the off-chain stored evidence package from clean backup
        or freshly re-compiles from DB to restore authentic status.
        """
        db = SessionLocal()
        try:
            pkg_model = db.query(EvidencePackageModel).filter(
                EvidencePackageModel.evidence_id == evidence_id
            ).first()

            if not pkg_model:
                raise ValueError(f"Evidence package {evidence_id} not found")

            # Check clean backup
            incident_dir = self._get_incident_storage_dir(pkg_model.incident_id)
            backup_file = incident_dir / f"{evidence_id}.manifest.clean_backup.json"
            manifest_file = Path(pkg_model.manifest_path)
            package_file = Path(pkg_model.storage_path)

            if backup_file.exists():
                shutil.copyfile(backup_file, manifest_file)
                with open(manifest_file, "rb") as f:
                    clean_manifest = json.loads(f.read().decode("utf-8"))
            else:
                clean_manifest = self.build_evidence_manifest(pkg_model.incident_id, pkg_model.version)
                clean_bytes = evidence_hash_service.canonicalize(clean_manifest)
                with open(manifest_file, "wb") as f:
                    f.write(clean_bytes)

            # Re-save full package file
            package_payload = {
                "evidence_package_id": evidence_id,
                "incident_id": pkg_model.incident_id,
                "version": pkg_model.version,
                "created_at": pkg_model.created_at.isoformat(),
                "created_by": pkg_model.created_by,
                "role": pkg_model.role,
                "hash_algorithm": "SHA-256",
                "evidence_hash": evidence_hash_service.calculate_sha256(clean_manifest)["hash"],
                "manifest": clean_manifest,
            }
            with open(package_file, "w", encoding="utf-8") as f:
                json.dump(package_payload, f, indent=2)

            pkg_model.status = "ANCHORED"

            # Audit Log
            total_logs = db.query(EvidenceAuditLogModel).count()
            audit_log = EvidenceAuditLogModel(
                log_id=f"LOG-EVD-{total_logs + 1:04d}",
                evidence_id=evidence_id,
                incident_id=pkg_model.incident_id,
                action="EVIDENCE_RESTORED",
                operator_id="DEMO_OPERATOR",
                role="ADMIN",
                timestamp=datetime.now(timezone.utc),
                metadata_json=json.dumps({"restored_at": datetime.now(timezone.utc).isoformat()})
            )
            db.add(audit_log)
            db.commit()

            return {
                "status": "success",
                "message": "Original authentic evidence package successfully restored.",
                "evidence_id": evidence_id,
            }
        finally:
            db.close()

    def get_evidence_packages(self, incident_id: str) -> List[EvidencePackageResponse]:
        """Returns all evidence package versions generated for an incident."""
        db = SessionLocal()
        try:
            packages = db.query(EvidencePackageModel).filter(
                EvidencePackageModel.incident_id == incident_id
            ).order_by(EvidencePackageModel.id.desc()).all()

            results = []
            for pkg in packages:
                h = db.query(EvidenceHashModel).filter(EvidenceHashModel.evidence_id == pkg.evidence_id).first()
                anchor = ledger_service.get_anchor(pkg.evidence_id)
                manifest = self.get_evidence_manifest(pkg.evidence_id)
                results.append(self._build_package_response(pkg, h, anchor, manifest))
            return results
        finally:
            db.close()

    def get_evidence_package(self, evidence_id: str) -> Optional[EvidencePackageResponse]:
        """Returns detailed evidence package response by evidence ID."""
        db = SessionLocal()
        try:
            pkg = db.query(EvidencePackageModel).filter(
                EvidencePackageModel.evidence_id == evidence_id
            ).first()
            if not pkg:
                return None
            h = db.query(EvidenceHashModel).filter(EvidenceHashModel.evidence_id == pkg.evidence_id).first()
            anchor = ledger_service.get_anchor(pkg.evidence_id)
            manifest = self.get_evidence_manifest(pkg.evidence_id)
            return self._build_package_response(pkg, h, anchor, manifest)
        finally:
            db.close()

    def get_evidence_manifest(self, evidence_id: str) -> Dict[str, Any]:
        """Retrieves the full manifest JSON from off-chain storage."""
        db = SessionLocal()
        try:
            pkg = db.query(EvidencePackageModel).filter(
                EvidencePackageModel.evidence_id == evidence_id
            ).first()
            if not pkg:
                raise ValueError(f"Evidence package {evidence_id} not found")

            package_file = Path(pkg.storage_path)
            if package_file.exists():
                with open(package_file, "r", encoding="utf-8") as f:
                    payload = json.load(f)
                return payload.get("manifest", {})

            # Fallback rebuild
            return self.build_evidence_manifest(pkg.incident_id, pkg.version)
        finally:
            db.close()

    def get_evidence_audit_trail(self, evidence_id: str) -> List[EvidenceAuditLogResponse]:
        """Returns the immutable audit log for an evidence package."""
        db = SessionLocal()
        try:
            logs = db.query(EvidenceAuditLogModel).filter(
                EvidenceAuditLogModel.evidence_id == evidence_id
            ).order_by(EvidenceAuditLogModel.timestamp.desc()).all()

            return [
                EvidenceAuditLogResponse(
                    log_id=l.log_id,
                    evidence_id=l.evidence_id,
                    incident_id=l.incident_id,
                    action=l.action,
                    operator_id=l.operator_id,
                    role=l.role,
                    timestamp=l.timestamp.isoformat(),
                    metadata=l.log_metadata
                )
                for l in logs
            ]
        finally:
            db.close()

    def _build_package_response(
        self,
        pkg: EvidencePackageModel,
        h: Optional[EvidenceHashModel],
        anchor: Optional[Dict[str, Any]],
        manifest: Dict[str, Any]
    ) -> EvidencePackageResponse:
        inclusion = EvidenceInclusionSummary(
            incident_metadata=bool(manifest.get("incident")),
            verified_events_count=len(manifest.get("events", [])),
            cameras_involved_count=len(manifest.get("journey", {}).get("cameras_sequence", [])),
            subject_journey_included=bool(manifest.get("journey")),
            risk_assessment_included=bool(manifest.get("risk_assessment")),
            operator_actions_count=len(manifest.get("operator_actions", [])),
            operator_notes_count=len(manifest.get("operator_notes", [])),
            media_references_count=len(manifest.get("media_references", [])),
        )

        hash_resp = EvidenceHashResponse(
            evidence_id=pkg.evidence_id,
            algorithm=h.algorithm if h else "SHA-256",
            hash_value=h.hash_value if h else "",
            canonical_size_bytes=h.canonical_size_bytes if h else 0,
            created_at=h.created_at.isoformat() if h else pkg.created_at.isoformat()
        )

        anchor_resp = None
        if anchor:
            anchor_resp = LedgerAnchorResponse(
                transaction_id=anchor["transaction_id"],
                evidence_id=anchor["evidence_id"],
                incident_id=anchor["incident_id"],
                version=anchor["version"],
                block_number=anchor["block_number"],
                block_hash=anchor["block_hash"],
                previous_block_hash=anchor["previous_block_hash"],
                anchored_hash=anchor["anchored_hash"],
                ledger_type=anchor["ledger_type"],
                timestamp=anchor["timestamp"],
                status=anchor["status"],
            )

        return EvidencePackageResponse(
            evidence_id=pkg.evidence_id,
            incident_id=pkg.incident_id,
            version=pkg.version,
            status=pkg.status,
            storage_path=pkg.storage_path,
            manifest_path=pkg.manifest_path,
            created_at=pkg.created_at.isoformat(),
            created_by=pkg.created_by,
            role=pkg.role,
            hash=hash_resp,
            anchor=anchor_resp,
            inclusion_summary=inclusion
        )


